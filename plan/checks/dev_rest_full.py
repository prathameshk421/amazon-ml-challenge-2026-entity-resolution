"""Full-scale learning-curve point: train x1_strsim's frozen 68-feature set on the entire MATCH_ALL
(VALIDATION_PLAN.md definition: MATCH_TRAIN + MATCH_VALID + DEV_REST = 1,655,458 S1), instead of just
MATCH_TRAIN's 180,000 (10.9%).

Reuses the 180,000-S1 DEV_REST slice already generated by dev_rest_180k.py (work/candidates/DEV_REST_180K/)
and generates candidates + features for the REMAINING 1,275,458 DEV_REST S1
(work/candidates/DEV_REST_REST/), the same way. MATCH_VALID's candidates/features already exist from the
normal pipeline and are reused as-is (not regenerated).

Round cap raised to 4000 (from match.json's 3000) for this run only: two of five folds hit the 3000 cap
without early stopping at the 360,000-S1 point, so a fair measurement at 1.65M needs headroom. This does
not change configs/match.json or work/match/models/ -- purely a local override inside this script.

Run from the repository root (this is the long step -- candidate generation for ~1.27M new S1 is the
dominant cost, est. ~2h on this machine's 6 workers):
  PYTHONPATH=submission/code/business_entity_resolution/src .venv/bin/python plan/checks/dev_rest_full.py
"""
import time

import lightgbm as lgb
import numpy as np
from sklearn.isotonic import IsotonicRegression
from sklearn.model_selection import GroupKFold, GroupShuffleSplit

from ber import io_utils, match, splits
from dev_rest_180k import (SEED, N_NEW as N_ALREADY, build_features, generate_candidates,
                           pick_dev_rest_slice)

SET_NAME_REST = "DEV_REST_REST"
NUM_BOOST_ROUND_OVERRIDE = 4000


def pick_remaining_slice():
    dev_rest = splits.load_query_sets()["DEV_REST"]
    already = pick_dev_rest_slice()  # same SEED -> same 180,000 already generated, reused not repeated
    remaining = np.setdiff1d(dev_rest, already, assume_unique=True)
    assert remaining.size == dev_rest.size - N_ALREADY, (remaining.size, dev_rest.size)
    return remaining.astype(np.int32), already


def train_full(packs, mcfg, threads, lg):
    X = np.concatenate([p[0] for p in packs])
    s1 = np.concatenate([p[1] for p in packs])
    pool = np.concatenate([p[2] for p in packs])
    y = np.concatenate([p[3] for p in packs])
    queries = np.sort(np.concatenate([p[4] for p in packs]))
    lg.info("MATCH_ALL assembled: %d S1, %d rows", queries.size, y.size)
    t0 = time.time()

    oof = np.zeros(y.size, dtype=np.float64)
    gkf = GroupKFold(n_splits=mcfg["n_folds"], shuffle=True, random_state=mcfg["fold_seed"])
    fold_info = []
    for k, (tr, te) in enumerate(gkf.split(X, y, s1)):
        gss = GroupShuffleSplit(n_splits=1, test_size=mcfg["early_stop_frac"],
                                random_state=mcfg["fold_seed"] + k)
        fit_i, es_i = next(gss.split(tr, groups=s1[tr]))
        fit_i, es_i = tr[fit_i], tr[es_i]
        dfit = lgb.Dataset(X[fit_i], label=y[fit_i], feature_name=match.FEATURES, free_raw_data=False)
        des = lgb.Dataset(X[es_i], label=y[es_i], reference=dfit, free_raw_data=False)
        params = {k2: v for k2, v in mcfg["lgb"].items()
                  if k2 not in ("num_boost_round", "early_stopping_rounds", "holdout_frac")}
        params["num_threads"] = threads
        booster = lgb.train(params, dfit, num_boost_round=NUM_BOOST_ROUND_OVERRIDE,
                            valid_sets=[des], valid_names=["early_stop"],
                            callbacks=[lgb.early_stopping(mcfg["early_stopping_rounds"], verbose=False),
                                      lgb.log_evaluation(period=0)])
        oof[te] = booster.predict(X[te], num_iteration=booster.best_iteration)
        fold_info.append({"fold": k, "best_iteration": int(booster.best_iteration), "n_fit_rows": int(fit_i.size),
                          "hit_cap": booster.best_iteration >= NUM_BOOST_ROUND_OVERRIDE})
        print(f"    fold {k}: best_iteration {booster.best_iteration}"
              f"{' (HIT CAP)' if booster.best_iteration >= NUM_BOOST_ROUND_OVERRIDE else ''} "
              f"({time.time()-t0:.0f}s)", flush=True)

    iso = IsotonicRegression(y_min=0.0, y_max=1.0, out_of_bounds="clip").fit(oof, y)
    p_cal = np.interp(oof, iso.X_thresholds_, iso.y_thresholds_).astype(np.float32)

    scorer = match.Scorer(queries, s1, y, match.true_counts(queries))
    dcfg = mcfg["decision"]
    grid = match.threshold_grid(dcfg)
    candidates = {}
    for owner in (False, True):
        pc = match.one_owner(pool, p_cal) if owner else p_cal
        sweep = {float(t): scorer.f05(pc >= t) for t in grid}
        t_best = max(sweep, key=sweep.get)
        candidates[owner] = (t_best, sweep[t_best])
    use_owner = candidates[True][1] > candidates[False][1]
    t_best, f05 = candidates[use_owner]
    report, _ = scorer.report(match.apply_decision({"rule": "threshold", "threshold": t_best,
                                                     "one_owner": use_owner}, s1, pool, p_cal), p_cal)
    return {"n_queries": int(queries.size), "n_rows": int(y.size), "oof_f05": float(f05),
            "threshold": t_best, "one_owner": bool(use_owner), "folds": fold_info,
            "num_boost_round_override": NUM_BOOST_ROUND_OVERRIDE,
            "any_fold_hit_cap": any(f["hit_cap"] for f in fold_info),
            "loss_breakdown": report["loss_breakdown"], "segments_report": {
                k: v for k, v in report.items() if k in ("singleton_accuracy", "candidate_recall_retained")},
            "wall_s": round(time.time() - t0, 1)}


def main():
    cfg, mcfg = io_utils.load_config(), match.load_match_config()
    lg = io_utils.get_logger("dev_rest_full")
    fp = match.bucketing_fingerprint(cfg)
    t_start = time.time()

    s1_rest, s1_already = pick_remaining_slice()
    import dev_rest_180k as d180
    d180.SET_NAME = SET_NAME_REST  # both generate_candidates and build_features key off this global --
                                   # must be set before EITHER call, or candidates for the 1.27M-S1
                                   # remaining slice would be written into the already-finished
                                   # DEV_REST_180K directory instead of their own DEV_REST_REST one.
    print(f">>> {time.strftime('%H:%M:%S')} generating candidates for {s1_rest.size} remaining DEV_REST "
          f"S1 (this is the long step, est. ~2h) ...", flush=True)
    generate_candidates(s1_rest, cfg, lg)
    print(f">>> {time.strftime('%H:%M:%S')} building features for the remaining slice ...", flush=True)
    build_features(s1_rest, cfg, mcfg, lg)
    d180.SET_NAME = "DEV_REST_180K"  # restore, so a re-run of dev_rest_180k.py in the same process (n/a
                                     # here, but cheap safety) would not be affected

    print(f">>> {time.strftime('%H:%M:%S')} loading all four feature sets and training on MATCH_ALL "
          f"(1,655,458 S1) ...", flush=True)
    packs = []
    for set_name, s1_arr in (("MATCH_TRAIN", None), ("MATCH_VALID", None),
                             ("DEV_REST_180K", s1_already), (SET_NAME_REST, s1_rest)):
        X, s1, pool, meta = match.load_features(set_name, fp)
        queries = s1_arr if s1_arr is not None else match.set_queries(set_name)
        packs.append((X, s1, pool, match.pair_labels(s1, pool), queries))
        print(f"    {set_name}: {queries.size} S1, {X.shape[0]} rows", flush=True)

    pt = train_full(packs, mcfg, io_utils.n_workers(cfg), lg)
    print(f"n=1655458 (MATCH_ALL): OOF F0.5 {pt['oof_f05']:.5f} (t={pt['threshold']}, "
          f"one_owner={pt['one_owner']}, any_fold_hit_cap={pt['any_fold_hit_cap']}, {pt['wall_s']}s)")
    print(f"total wall (candidates+features+train): {time.time()-t_start:.0f}s")

    curve_path = io_utils.paths()["metrics_root"] / "learning_curve.json"
    doc = io_utils.read_json(curve_path)
    points = doc["points"]
    points.append(dict(pt, source="dev_rest_full.py: full MATCH_ALL (MATCH_TRAIN+MATCH_VALID+DEV_REST)"))
    io_utils.write_metrics("learning_curve", {"points": points, "note": doc.get("note")}, 0, 0, cfg)
    print(f"updated {curve_path}")


if __name__ == "__main__":
    main()
